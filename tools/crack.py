#!/usr/bin/env python3
"""Generate and byte-check one m2c candidate against Block.elf.

    python tools/crack.py 02015FCC 02015FF0
    python tools/crack.py --src src/fn_02015FCC.c
    python tools/crack.py --src src/fn_02015FCC.c --sweep

Unlike tools/match.py, which checks the registered table, this starts from an
address range: it slices main.s, runs m2c in valid-syntax mode, wraps the
result with the shared types and m2c macros, compiles it with GHS ccppc,
applies the object's relocations, and prints an instruction-aligned
target/object diff. The candidate is written to build/crack/ unless --save is
given. Call-bearing functions therefore work without hand-patching REL24.

A match is reported only when every byte and the size agree. The generated C is
a first pass, not a finished function: m2c leaves unknown field widths as
M2C_FIELD/M2C_UNK, and calls or globals still need declarations. The script
does not invent types or claim a match from similar-looking instructions.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fn2m2c
import match

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_DIR = os.path.join(ROOT, "include")
TABLE = os.path.join(ROOT, "src", "functions.tsv")
DEFAULT_OBJDUMP = os.environ.get("OBJDUMP", "powerpc-eabi-objdump")
SWEEP = ["-O1", "-O2", "-O3", "-Ogeneral", "-Ospeed", "-Ospace"]

FALLBACK_MACROS = r"""/* Fallback subset of m2c's m2c_macros.h. */
#ifndef M2C_MACROS_H
#define M2C_MACROS_H
typedef s32 M2C_UNK;
typedef s8  M2C_UNK8;
typedef s16 M2C_UNK16;
typedef s32 M2C_UNK32;
typedef s64 M2C_UNK64;
#define M2C_FIELD(expr, type_ptr, offset) (*(type_ptr)((s8 *)(expr) + (offset)))
#define M2C_BITWISE(type, expr) ((type)(expr))
#define M2C_LWL(expr) (expr)
#define M2C_FIRST3BYTES(expr) (expr)
#define M2C_UNALIGNED32(expr) (expr)
#define M2C_ERROR(desc) (0)
#define M2C_TRAP_IF(cond) (0)
#define M2C_BREAK() (0)
#endif
"""

CANDIDATE_HEADER = """/* Generated by tools/crack.py for 0x%08X..0x%08X.
   m2c valid-syntax first pass; not verified until the bytes match. */
#include "block.h"
#include <string.h>

%s

%s"""


def read_text(path):
    with open(path, encoding="utf-8", errors="replace", newline="") as f:
        return f.read().replace("\r\n", "\n")


def write_text(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def rooted(path):
    return path if os.path.isabs(path) else os.path.join(ROOT, path)


def m2c_macros(m2c_path):
    header = os.path.join(os.path.dirname(os.path.abspath(m2c_path)), "m2c_macros.h")
    return read_text(header) if os.path.exists(header) else FALLBACK_MACROS


def find_objdump(explicit):
    if explicit:
        return explicit
    if os.path.exists(DEFAULT_OBJDUMP):
        return DEFAULT_OBJDUMP
    return shutil.which(DEFAULT_OBJDUMP)


def find_table_row(rows, name=None, src=None):
    if name:
        for row in rows:
            if row[0] == name:
                return row
        raise SystemExit("no %s in %s" % (name, TABLE))
    if src:
        wanted = os.path.normcase(os.path.abspath(rooted(src)))
        for row in rows:
            if os.path.normcase(os.path.abspath(os.path.join(ROOT, row[3]))) == wanted:
                return row
    return None


def function_name(path):
    """Best-effort name of the first function definition in a source file."""
    text = read_text(path)
    skip = {"if", "for", "while", "switch", "sizeof"}
    for m in re.finditer(
            r"(?m)^[ \t]*(?:static[ \t]+)?(?:[A-Za-z_]\w*[ \t*]+)+"
            r"([A-Za-z_]\w*)[ \t]*\([^;{}]*\)[ \t]*\{", text):
        if m.group(1) not in skip:
            return m.group(1)
    return None


def resolve(args):
    rows = match.load_table(TABLE)
    row_for_src = find_table_row(rows, src=args.src) if args.src else None
    row = row_for_src
    if args.name:
        named = next((r for r in rows if r[0] == args.name), None)
        if named is not None:
            row = named
        elif row is None and not (args.start and args.end):
            raise SystemExit("no %s in %s" % (args.name, TABLE))

    start = fn2m2c.parse_addr(args.start) if args.start else (row[1] if row else None)
    end = fn2m2c.parse_addr(args.end) if args.end else (row[2] if row else None)
    if start is None or end is None:
        raise SystemExit("give START END, or a table name/source with a known range")
    if end < start:
        raise SystemExit("end 0x%08X is before start 0x%08X" % (end, start))
    if (end - start + 4) % 4:
        raise SystemExit("range 0x%08X..0x%08X is not a whole number of instructions"
                         % (start, end))

    if args.src:
        source = os.path.abspath(rooted(args.src))
        if not os.path.exists(source):
            raise SystemExit("source not found: %s" % source)
        symbol = args.name or (row_for_src[0] if row_for_src else function_name(source))
        if not symbol:
            raise SystemExit("cannot find a function name in %s; pass --name" % source)
        return start, end, source, symbol, row_for_src

    symbol = args.name or "func_%08X" % start
    return start, end, None, symbol, row


def generate(args, start, end, outdir):
    insns = fn2m2c.slice_function(args.asm, start, end)
    if not insns:
        raise SystemExit("no instructions in 0x%08X..0x%08X" % (start, end))
    asm_text, label = fn2m2c.render(insns)
    asm_path = os.path.join(outdir, label + ".s")
    write_text(asm_path, asm_text)

    cmd = [sys.executable, args.m2c, "-t", args.target, "-f", label,
           "--valid-syntax"] + args.m2c_arg + [asm_path]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode:
        print("m2c failed (exit %d):" % result.returncode)
        for line in (result.stderr or result.stdout).strip().splitlines()[:12]:
            print("  " + line)
        raise SystemExit(1)
    if result.stderr.strip():
        for line in result.stderr.strip().splitlines()[:6]:
            print("m2c: " + line)
    body = fix_indexed_fields(result.stdout.replace("\r\n", "\n")).rstrip() + "\n"
    if not body.strip():
        raise SystemExit("m2c produced no source")
    text = CANDIDATE_HEADER % (start, end, m2c_macros(args.m2c), body)
    return text, label, asm_path


def compile_one(cc, opt, src, obj):
    opt = opt if opt.startswith("-") else "-" + opt
    cmd = [cc, "-c", opt, "-I" + INCLUDE_DIR, src, "-o", obj]
    return subprocess.run(cmd, capture_output=True, text=True)


def checked_object(elf, target, obj_path, symbol, start, symbols):
    try:
        obj_elf = match.Elf(obj_path)
    except SystemExit as exc:
        print("object is not an ELF: %s" % exc)
        return None
    value, _size = obj_elf.symbol(symbol)
    if value is None:
        print("no symbol %s in %s" % (symbol, obj_path))
        return None
    got = match.object_bytes(obj_path, symbol)
    got, applied, unresolved, unresolved_sites = match.apply_relocations(
        got, start, obj_elf, value, symbols, elf)
    status, same, total, first, exact = match.classify(
        target, got, unresolved_sites)
    if status == "BLOCKED":
        print("BLOCKED %s: unresolved relocations: %s"
              % (symbol, ", ".join(unresolved[:4])))
        return None
    if applied:
        print("  %d relocation(s) applied" % len(applied))
    if unresolved:
        print("  %d unresolved relocation(s); difference outside them"
              % len(unresolved))
    return (same, total, first, exact), got


def decode(blob, objdump, outdir):
    if not objdump:
        return []
    fd, path = tempfile.mkstemp(prefix=".crack_", suffix=".bin", dir=outdir)
    os.close(fd)
    try:
        with open(path, "wb") as f:
            f.write(blob)
        result = subprocess.run(
            [objdump, "-D", "-b", "binary", "-m", "powerpc", "-EB", path],
            capture_output=True, text=True)
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass
    if result.returncode:
        return []
    out = []
    for line in result.stdout.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}\s+)+)(.*)$", line)
        if not m:
            continue
        raw = "".join(m.group(2).split())
        if len(raw) != 8:
            continue
        out.append((int(m.group(1), 16), raw, m.group(3).strip()))
    return out


def cut(text, width=38):
    return text if len(text) <= width else text[:width - 1] + "~"


def print_diff(target, got, start, objdump, outdir):
    t = decode(target, objdump, outdir)
    o = decode(got, objdump, outdir)
    if not t or not o:
        print("  target bytes: %s" % target.hex(" "))
        print("  object bytes: %s" % got.hex(" "))
        if not objdump:
            print("  (objdump not found; install devkitPPC or pass --objdump)")
        return

    print("  offset  target                              object")
    for i in range(max(len(t), len(o))):
        ta = t[i] if i < len(t) else None
        oa = o[i] if i < len(o) else None
        marker = "=" if ta and oa and ta[1] == oa[1] else "!"
        left = "+0x%02X  %s  %-38s" % (ta[0], ta[1], cut(ta[2])) if ta else " " * 49
        right = "%s  %-38s" % (oa[1], cut(oa[2])) if oa else ""
        print("  %s | %s %s" % (left, right, marker))


def fix_indexed_fields(text):
    """Rewrite m2c's invalid `*((i * 4) + M2C_FIELD(...))` form.

    m2c valid-syntax mode leaves the field expression as a value instead of a
    pointer, so C rejects the dereference. Folding the index into the byte
    offset produces the same lvalue through M2C_FIELD.
    """
    pattern = re.compile(
        r"\*\(\s*\(([^()]+?)\s*\*\s*(\d+)\)\s*\+\s*"
        r"M2C_FIELD\(([^,]+),\s*([^,]+),\s*(0x[0-9A-Fa-f]+|\d+)\)\s*\)")

    def repl(m):
        index, scale, expr, typ, offset = m.groups()
        return "M2C_FIELD(%s, %s, %s + (%s * %s))" % (
            expr, typ, offset, index, scale)

    return pattern.sub(repl, text)



def run(args):
    elf = match.Elf(args.elf)
    symbols = match.load_symbols(args.symbols)
    start, end, source, symbol, row = resolve(args)
    target = elf.read(start, end - start + 4)
    outdir = os.path.abspath(rooted(args.outdir))
    os.makedirs(outdir, exist_ok=True)

    print("== %s  0x%08X..0x%08X  (%d B) ==" % (symbol, start, end, len(target)))

    if source:
        candidate = source
        print("source   %s" % candidate)
    else:
        if args.save:
            candidate = os.path.abspath(rooted(args.save))
        else:
            candidate = os.path.join(outdir, symbol + ".c")
        text, generated_symbol, asm_path = generate(args, start, end, outdir)
        if generated_symbol != symbol:
            symbol = generated_symbol
            if not args.save:
                candidate = os.path.join(outdir, symbol + ".c")
        write_text(candidate, text)
        print("m2c      %s" % asm_path)
        print("candidate %s" % candidate)

    opts = SWEEP if args.sweep else [args.opt]
    results = []
    for opt in opts:
        tag = opt if opt.startswith("-") else "-" + opt
        obj_path = os.path.join(outdir, symbol + "_" + tag.lstrip("-") + ".o")
        compiled = compile_one(args.cc, tag, candidate, obj_path)
        if compiled.returncode:
            print("BLOCKED %s: compiler failed (exit %d)" % (tag, compiled.returncode))
            for line in (compiled.stderr or compiled.stdout).strip().splitlines()[:12]:
                print("  " + line)
            return 2
        checked = checked_object(elf, target, obj_path, symbol, start, symbols)
        if checked is None:
            return 1
        (same, total, first, exact), got = checked
        results.append({
            "opt": tag, "same": same, "total": total, "first": first,
            "exact": exact, "got": got,
        })
        print("  %-10s %2d/%2d words  %3d B%s"
              % (tag, same, total, len(got), "  MATCH" if exact else ""))

    def score(result):
        return (result["exact"], result["same"],
                -abs(len(result["got"]) - len(target)))

    best = max(results, key=score)
    print("best %s: %d/%d words, %d B" %
          (best["opt"], best["same"], best["total"], len(best["got"])))
    if best["first"] is not None:
        off = best["first"] * 4
        print("first diff +0x%X: target %s, object %s"
              % (off, target[off:off + 4].hex(), best["got"][off:off + 4].hex()))
    print_diff(target, best["got"], start, find_objdump(args.objdump), outdir)

    if best["exact"]:
        print("MATCH %s at %s" % (symbol, best["opt"]))
    else:
        print("NO MATCH -- candidate still needs work")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Generate an m2c candidate, compile it with GHS, and diff it.")
    ap.add_argument("start", nargs="?", help="first address, e.g. 02015FCC")
    ap.add_argument("end", nargs="?", help="last address, inclusive")
    ap.add_argument("--name", help="registered function name, or symbol for --src")
    ap.add_argument("--src", help="existing C source; skips m2c generation")
    ap.add_argument("--save", help="write the generated candidate to this path")
    ap.add_argument("--sweep", action="store_true",
                    help="try the six common -O levels")
    ap.add_argument("--opt", default="-O2", help="optimisation flag (default: -O2)")
    ap.add_argument("--asm", default=fn2m2c.DEFAULT_ASM, help="main.s listing")
    ap.add_argument("--m2c", default=fn2m2c.DEFAULT_M2C, help="path to m2c.py")
    ap.add_argument("--m2c-arg", action="append", default=[], metavar="ARG",
                    help="extra m2c argument, repeatable (e.g. --no-andor)")
    ap.add_argument("--cc", default=match.DEFAULT_CC, help="Green Hills ccppc")
    ap.add_argument("--elf", default=match.DEFAULT_ELF, help="reference Block.elf")
    ap.add_argument("--symbols", default=match.DEFAULT_SYMBOLS,
                    help="relative symbol map for relocations")
    ap.add_argument("--objdump", help="devkitPPC objdump for the instruction diff")
    ap.add_argument("--outdir", default=os.path.join(ROOT, "build", "crack"),
                    help="candidate/object output directory")
    ap.add_argument("-t", "--target", default="ppc", help="m2c target (default: ppc)")
    args = ap.parse_args(argv)

    if args.src and args.save:
        ap.error("--save only applies to generated candidates")
    if args.src is None and (not args.start or not args.end):
        ap.error("START and END are required when generating with m2c")
    try:
        return run(args)
    except SystemExit:
        raise
    except Exception as exc:
        print("crack: %s" % exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
