#!/usr/bin/env python3
"""Archive non-MATCH batch candidates under src/near.

The batch runner writes candidates and results to build/, which is ignored.
This tool copies every non-MATCH candidate source into a tracked near directory
and writes a small deterministic README. It never registers a candidate in the
verification table.
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "batch"


def sanitize_detail(text):
    """Replace a local workspace prefix in a compiler diagnostic."""
    while True:
        starts = [
            i
            for i in (
                text.find("C:" + chr(92)),
                text.find("/home/"),
                text.find("/Users/"),
            )
            if i != -1
        ]
        if not starts:
            return text
        start = min(starts)
        build = text.find("build", start)
        if build == -1:
            return text
        batch = text.find("batch", build)
        if batch == -1:
            return text
        end = batch + len("batch")
        while end < len(text) and text[end] in (chr(92), "/"):
            end += 1
        text = text[:start] + "build/batch/" + text[end:]


def parse_results(path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 9:
            continue
        name, start, end, size, status, words, total, first, detail = fields
        if status == "MATCH":
            continue
        rows.append(
            {
                "name": name,
                "start": start,
                "end": end,
                "size": size,
                "status": status,
                "words": words,
                "total": total,
                "first": first,
                "detail": sanitize_detail(detail).replace("|", chr(92) + "|"),
            }
        )
    return rows


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--band", required=True, help="band label, e.g. 02800000..02820000")
    parser.add_argument("--label", default="candidates", help="subdirectory label")
    parser.add_argument("--results", default=str(BUILD / "results.tsv"))
    parser.add_argument("--out", required=True, help="path under the repository")
    args = parser.parse_args()

    results = Path(args.results)
    if not results.is_file():
        raise SystemExit(f"no results file: {results}")
    rows = parse_results(results)
    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)
    copied = 0
    missing = []
    for row in rows:
        source = BUILD / (row["name"] + ".c")
        if not source.is_file():
            missing.append(row["name"])
            row["file"] = "—"
            continue
        shutil.copyfile(source, out / (row["name"] + ".c"))
        row["file"] = f"`{row['name']}.c`"
        copied += 1

    lines = [
        f"# Near candidates for `0x{args.band}` ({args.label})",
        "",
        "Generated by `tools/batch.py` and archived from the ignored `build/` tree.",
        "Every row below is a non-match and is **not** claimed in",
        "`src/functions.tsv`.",
        "",
        f"- Candidates archived: **{len(rows)}**",
        f"- Source files copied: **{copied}**",
        f"- Missing generated sources: **{len(missing)}**",
        "",
        "| Function | Range | Bytes | Status | Words | First diff | File | Detail |",
        "|---|---|---:|---|---:|---|---|---|",
    ]
    for row in rows:
        words = f"{row['words']}/{row['total']}" if row["total"] != "0" else "—"
        first = row["first"] or "—"
        detail = row["detail"] or "—"
        lines.append(
            f"| `{row['name']}` | `{row['start']}..{row['end']}` | {row['size']} | "
            f"{row['status']} | {words} | {first} | {row['file']} | {detail} |"
        )
    if missing:
        lines += ["", "Missing sources: " + ", ".join(f"`{name}`" for name in missing)]
    lines += ["", "Regenerate the batch before changing any row; this directory is evidence only."]
    (out / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"archived {len(rows)} non-matches ({copied} sources) in {out}")


if __name__ == "__main__":
    main()
